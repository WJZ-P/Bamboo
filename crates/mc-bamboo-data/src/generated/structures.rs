/// 按注册名取模板的 gzip 字节，交给 `mc-bamboo-nbt::read_compressed` 解析。
///
/// Look up a template's gzip bytes by id; feed them to `read_compressed`.
pub fn get(name: &str) -> Option<&'static [u8]> {
    let index = ENTRIES.binary_search_by(|(id, _, _)| (*id).cmp(name)).ok()?;
    let (_, start, len) = ENTRIES[index];
    Some(&BLOB[start as usize..(start + len) as usize])
}
